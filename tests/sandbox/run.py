"""`make sandbox`: run every scenario + determinism check, print a table, write reports/sandbox_report.md.

Status per case:
  PASS        expectations met and deterministic
  FAIL        expectations not met and no bug filed  -> exit 1
  BUG-xx      known bug reproduced (tracked, xfail in pytest)
  XPASS       a filed bug no longer reproduces -> remove `bug:` from the scenario  -> exit 1
"""

from __future__ import annotations

import logging
import subprocess
import sys
import warnings
from datetime import datetime
from pathlib import Path

from tests.sandbox.harness import FROZEN_NOW, determinism, load_scenarios, run_case, run_unseeded_twice

ROOT = Path(__file__).resolve().parents[2]
RUNS = 5


def _status(failed: bool, bug: str | None) -> str:
    if bug:
        return bug if failed else "XPASS"
    return "FAIL" if failed else "PASS"


def main() -> int:
    warnings.filterwarnings("ignore")
    logging.disable(logging.CRITICAL)
    rows = []
    for case in sorted(load_scenarios(), key=lambda c: c["id"]):
        res = run_case(case)
        det = determinism(case, runs=RUNS)
        rows.append({
            "id": case["id"], "area": case["area"], "title": case["title"],
            "func": _status(not res.passed, case.get("bug")),
            "det": _status(bool(det), case.get("determinism_bug")),
            "failures": res.failures, "det_problems": det,
        })
    a, b = run_unseeded_twice(next(c for c in load_scenarios() if c["id"] == "SBX-01"))
    unseeded_same = a.transcript == b.transcript and a.final_state == b.final_state

    bad = [r for r in rows if r["func"] in ("FAIL", "XPASS") or r["det"] in ("FAIL", "XPASS")]
    n_pass = sum(r["func"] == "PASS" for r in rows)
    n_bug = sum(r["func"].startswith("BUG") for r in rows)
    n_det_ok = sum(r["det"] == "PASS" for r in rows)

    w = max(len(r["id"]) for r in rows)
    print(f"{'ID':<{w}}  {'functional':<10}  {'determinism':<11}  area")
    print("-" * 78)
    for r in rows:
        print(f"{r['id']:<{w}}  {r['func']:<10}  {r['det']:<11}  {r['area']}")
    print("-" * 78)
    print(f"{len(rows)} cases: {n_pass} pass, {n_bug} known bug, {len(bad)} unexpected | "
          f"determinism {n_det_ok}/{len(rows)} identical over {RUNS} fresh runs + {RUNS} shuffles | "
          f"unseeded uuid identical: {unseeded_same}")

    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                                text=True, check=False).stdout.strip()
    except OSError:
        commit = "?"
    out = [
        "# Sandbox report",
        "",
        f"Generated by `make sandbox` at commit `{commit}`. Frozen clock = {FROZEN_NOW} "
        f"({datetime.utcfromtimestamp(FROZEN_NOW):%Y-%m-%d %H:%M} UTC), no network, seeded uuid.",
        "",
        f"- Cases: **{len(rows)}** | pass **{n_pass}** | known bug (xfail) **{n_bug}** | unexpected **{len(bad)}**",
        f"- Determinism: **{n_det_ok}/{len(rows)}** byte-identical across {RUNS} fresh engines and "
        f"{RUNS} shuffled-but-equivalent setups",
        f"- Production session_id deterministic without sandbox seed: **{unseeded_same}** "
        f"{'' if unseeded_same else '(BUG-20)'}",
        "",
        "| ID | Area | Functional | Determinism | Title |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        out.append(f"| {r['id']} | {r['area']} | {r['func']} | {r['det']} | {r['title']} |")
    out += ["", "## Failure details (actual behaviour)", ""]
    for r in rows:
        if r["failures"] or r["det_problems"]:
            out.append(f"### {r['id']} ({r['func']} / {r['det']})")
            for f in r["failures"]:
                out.append(f"- {f}")
            for p in r["det_problems"][:4]:
                out.append(f"- determinism: {p}")
            out.append("")
    report = ROOT / "reports" / "sandbox_report.md"
    report.parent.mkdir(exist_ok=True)
    report.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {report.relative_to(ROOT)}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
